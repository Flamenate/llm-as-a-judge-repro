def _aggregate_cr(consistency, biases):
    rows = []
    for model in MODEL_ORDER:
        n = 0
        successes = 0.0
        failed = 0
        for bias in biases:
            hit = lookup(consistency, model=model, bias=bias)
            if not hit or hit.get("cr") in ("", None):
                continue
            n_cr = int(float(hit["n_cr"]))
            n += n_cr
            successes += float(hit["cr"]) * n_cr
            failed += int(float(hit["n_cr_failed"] or 0))
        if n == 0:
            continue
        cr = successes / n
        low, high = wilson_interval(successes, n)
        rows.append(
            [
                MODEL_LABELS[model],
                str(n),
                fnum(cr),
                fnum(low),
                fnum(high),
                str(failed),
            ]
        )
    return rows


