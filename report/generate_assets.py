def read_csv(name):
    with (ANALYSIS / name).open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def fnum(value, digits=3):
    if value is None or value == "":
        return "{---}"
    number = float(value)
    if math.isnan(number):
        return "{---}"
    return f"{number:.{digits}f}"


def wilson_interval(successes, n, z=WILSON_Z):
    if n <= 0:
        return float("nan"), float("nan")
    p = successes / n
    denominator = 1 + z * z / n
    center = (p + z * z / (2 * n)) / denominator
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / denominator
    return center - half, center + half


def write_table(name, caption, label, colspec, header, rows, notes=None, longtable=False):
    TABLES.mkdir(parents=True, exist_ok=True)
    lines = [f"% Auto-generated by generate_assets.py --- {name}"]
    if longtable:
        lines += [
            r"\begingroup",
            r"\footnotesize",
            r"\setlength{\tabcolsep}{3.5pt}",
            rf"\begin{{longtable}}{{{colspec}}}",
            rf"  \caption{{{caption}}}\\",
            rf"  \label{{{label}}}\\",
            r"  \toprule",
            "  " + " & ".join(header) + r" \\",
            r"  \midrule",
            r"  \endfirsthead",
            rf"  \caption[]{{{caption} (suite)}}\\",
            r"  \toprule",
            "  " + " & ".join(header) + r" \\",
            r"  \midrule",
            r"  \endhead",
            r"  \bottomrule",
            r"  \endfoot",
        ]
        for row in rows:
            lines.append("  " + " & ".join(row) + r" \\")
        lines += [
            r"\end{longtable}",
            r"\endgroup",
        ]
        if notes:
            lines.append(rf"\noindent\footnotesize {notes}")
            lines.append("")
    else:
        lines += [
            r"\begin{table}[htbp]",
            r"  \centering",
            r"  \small",
            rf"  \caption{{{caption}}}",
            rf"  \label{{{label}}}",
            r"  \sisetup{table-number-alignment=center}",
            rf"  \begin{{tabular}}{{{colspec}}}",
            r"    \toprule",
            "    " + " & ".join(header) + r" \\",
            r"    \midrule",
        ]
        for row in rows:
            lines.append("    " + " & ".join(row) + r" \\")
        lines += [
            r"    \bottomrule",
            r"  \end{tabular}",
        ]
        if notes:
            lines.append(rf"  \caption*{{\footnotesize {notes}}}")
        lines.append(r"\end{table}")
        lines.append("")
    (TABLES / name).write_text("\n".join(lines) + "\n", encoding="utf-8")


def copy_figures():
    FIGURES.mkdir(parents=True, exist_ok=True)
    copied = 0
    for src in sorted(ANALYSIS.glob("*.png")):
        shutil.copy2(src, FIGURES / src.name)
        copied += 1
    return copied


def lookup(rows, **kwargs):
    for row in rows:
        if all(row.get(key) == value for key, value in kwargs.items()):
            return row
    return None


