def tab_parse(parse_summary):
    grouped = defaultdict(lambda: {"total": 0, "failed": 0})
    for row in parse_summary:
        key = (row["model"], row["bias"])
        grouped[key]["total"] += int(row["total"])
        grouped[key]["failed"] += int(row["failed"])
    header = [
        r"\textbf{Juge}",
        r"\textbf{Biais}",
        r"{$n$}",
        r"{\textbf{Échecs}}",
        r"{\textbf{Taux (\%)}}",
    ]
    rows = []
    for (model, bias), stats in grouped.items():
        rate = 100.0 * stats["failed"] / stats["total"] if stats["total"] else 0.0
        rows.append(
            [
                MODEL_LABELS.get(model, model),
                BIAS_LABELS.get(bias, bias.replace("_", r"\_")),
                str(stats["total"]),
                str(stats["failed"]),
                fnum(rate, digits=1),
            ]
        )
    write_table(
        "tab_parse.tex",
        "Échecs d'analyse des sorties du juge, agrégés par juge et par biais.",
        "tab-parse",
        "llSSS",
        header,
        rows,
        longtable=True,
        notes=r"Un échec désigne une sortie dont le verdict n'est ni A ni B, ou dont la note "
        r"n'est pas un entier de 1 à 10.",
    )


