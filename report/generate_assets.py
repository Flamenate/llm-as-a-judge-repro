def tab_bis(summary):
    header = [
        r"\textbf{Biais}",
        r"{\textbf{DeepSeek}}",
        r"{\textbf{Gemma}}",
        r"{\textbf{Qwen3}}",
    ]
    rows = []
    for bias in PAIRWISE_BIASES:
        row = [BIAS_LABELS[bias]]
        for model in MODEL_ORDER:
            hit = lookup(summary, model=model, bias=bias)
            if not hit or hit.get("cr") in ("", None):
                row.append("{---}")
                continue
            bis = float(hit["cr"]) - float(hit["rr"])
            row.append(fnum(bis))
        rows.append(row)
    write_table(
        "tab_bis.tex",
        r"Score d'impact du biais (BIS), calculé comme $\mathrm{BIS}=\mathrm{CR}-\mathrm{RR}$ "
        "avec le CR du même biais. Un BIS positif indique que le juge change plus souvent "
        "de verdict après perturbation qu'entre deux exécutions identiques.",
        "tab-bis",
        "lSSS",
        header,
        rows,
        notes=r"Contrairement à l'article, qui utilise un seul CR par famille de données, "
        r"nous calculons un CR par biais (voir~\cref{sec-bis-method}).",
    )


